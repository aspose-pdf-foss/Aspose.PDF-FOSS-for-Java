package org.aspose.pdf;

/**
 * Page-layout adjustment applied when converting HTML to PDF
 * (API-compatible with Aspose.PDF {@code HtmlPageLayoutOption}).
 */
public enum HtmlPageLayoutOption {

    /** No layout adjustment (default). */
    None,

    /** Widen the page to the widest content width. */
    FitToWidestContentWidth,

    /** Scale content down to the page width. */
    ScaleToPageWidth
}
